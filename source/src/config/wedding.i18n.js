const isObject = (v) => v && typeof v === 'object' && !Array.isArray(v);

/** Lay a translation over the English details: objects key by key, lists by id (or position). */
function overlay(base, over) {
  if (over === undefined) return base;
  if (Array.isArray(base) && Array.isArray(over)) {
    const byId = base.every((b) => isObject(b) && b.id) && over.every((o) => isObject(o) && o.id);
    if (byId) return base.map((b) => overlay(b, over.find((o) => o.id === b.id)));
    if (base.every(isObject)) return base.map((b, i) => overlay(b, over[i]));
    return over;
  }
  if (isObject(base) && isObject(over)) {
    const out = { ...base };
    for (const key of Object.keys(over)) out[key] = overlay(base[key], over[key]);
    return out;
  }
  return over;
}

export function localizeWedding(wedding, language) {
  return overlay(wedding, weddingTranslations[language]);
}
